"""
relocaitor/datasets.py — Loads the country dataset from data/countries.csv.

Every country in data/world.csv (196) that has enough measured data to be ranked;
66 with the data committed today, more after `python -m pipeline fetch`. Each row has:
  - 10 normalized [0, 1] metrics (9 scoring factors + language_barrier, which is
    used for similarity and trade-off analysis only)
  - salary_usd_month: approximate average monthly NET salary in USD
  - rent_usd_month:   approximate 1-bedroom city-centre rent in USD

countries.csv is GENERATED by the data pipeline (`python -m pipeline build`) from
World Bank, WHO, EF EPI, Global Peace Index and climate data. Don't edit it by hand:
change the sources or methods in pipeline/ and rebuild. data/SOURCES.md documents
every column, and data/provenance.csv records the source and year of every value.
"""

import json
import os
from functools import lru_cache
from pathlib import Path

import pandas as pd
from relocaitor import paths

DATA_DIR = paths.DATA
# The generated dataset (countries.csv, provenance.csv, ml/country_map.json). Tests point this at a
# frozen 66-country snapshot so they don't change when you fetch data for more countries.
DATASET_DIR = Path(os.environ.get("RELOC_DATASET_DIR") or DATA_DIR)
COUNTRIES_CSV = DATASET_DIR / "countries.csv"

METRIC_COLUMNS = [
    "average_salary", "cost_of_living", "pr_ease", "job_market", "language_barrier",
    "climate", "safety", "healthcare", "english", "internet",
]
FIGURE_COLUMNS = ["salary_usd_month", "rent_usd_month"]
# Raw sourced figures shown in the UI (may be missing for some countries, e.g. Taiwan).
OPTIONAL_COLUMNS = ["gni_per_capita_usd", "price_level", "avg_temp_c", "main_city"]
COLUMNS = ["country_name", "country_code", "region"] + METRIC_COLUMNS + FIGURE_COLUMNS + OPTIONAL_COLUMNS
PROVENANCE_CSV = DATASET_DIR / "provenance.csv"
COUNTRY_MAP_JSON = DATASET_DIR / "ml" / "country_map.json"


@lru_cache(maxsize=1)
def _load_cached() -> pd.DataFrame:
    df = pd.read_csv(COUNTRIES_CSV)
    missing = [c for c in COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"countries.csv is missing columns: {missing}")
    df[METRIC_COLUMNS] = df[METRIC_COLUMNS].astype(float)
    df[FIGURE_COLUMNS] = df[FIGURE_COLUMNS].astype(int)
    for c in OPTIONAL_COLUMNS:  # missing values become None, so the API emits null (never NaN)
        df[c] = df[c].astype(object).where(df[c].notna(), None)
    return df[COLUMNS]


@lru_cache(maxsize=1)
def _provenance() -> dict:
    """{country_code: {column: {"method", "detail"}}} from data/provenance.csv (built by the pipeline)."""
    if not PROVENANCE_CSV.exists():
        return {}
    out = {}
    for r in pd.read_csv(PROVENANCE_CSV).itertuples(index=False):
        out.setdefault(r.country_code, {})[r.column] = {"method": r.method, "detail": r.detail}
    return out


def get_provenance(country_code: str) -> dict:
    return _provenance().get(country_code, {})


@lru_cache(maxsize=1)
def get_country_map() -> dict:
    """ML country landscape (PCA coordinates, clusters, nearest neighbours) built by the pipeline."""
    import json
    if not COUNTRY_MAP_JSON.exists():
        return {}
    return json.loads(COUNTRY_MAP_JSON.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def get_data_version() -> str:
    """The date of the dataset as a whole (data/version.json), shown with every result."""
    path = paths.DATA / "version.json"
    return json.loads(path.read_text(encoding="utf-8"))["data_version"]


def load_countries() -> pd.DataFrame:
    """Return a fresh copy of the dataset (cached on disk read, safe to mutate)."""
    return _load_cached().copy()


def get_regions() -> list:
    return sorted(_load_cached()["region"].unique().tolist())


def country_codes() -> set:
    return set(_load_cached()["country_code"])


def clear_cache() -> None:
    """Force the next load to re-read the CSV (used by tests and the update script)."""
    _load_cached.cache_clear()
    _provenance.cache_clear()
    get_world.cache_clear()
    get_country_map.cache_clear()


# ---------------------------------------------------------------------------
# The whole world: data/world.csv lists every country (ranked or not yet).
# ---------------------------------------------------------------------------

WORLD_CSV = DATA_DIR / "world.csv"


@lru_cache(maxsize=1)
def get_world() -> pd.DataFrame:
    """country_code, country_name, region, m49, iso2, capital, demonym, aliases, marker_lon, marker_lat."""
    return pd.read_csv(WORLD_CSV, comment="#", dtype={"m49": str}, keep_default_na=False)


def get_nationalities() -> list:
    """[{code, name, demonym}] for every country in the world list (passports aren't limited to ranked countries)."""
    w = get_world()
    return sorted(({"code": c, "name": n, "demonym": d}
                   for c, n, d in zip(w["country_code"], w["country_name"], w["demonym"])),
                  key=lambda x: x["name"])


def get_map_markers() -> dict:
    """{ISO-3: [lon, lat]} for ranked countries too small for the world map's outlines."""
    w = get_world()
    ranked = set(load_countries()["country_code"])
    return {r.country_code: [float(r.marker_lon), float(r.marker_lat)]
            for r in w.itertuples() if r.marker_lon != "" and r.country_code in ranked}
